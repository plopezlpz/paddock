#!/usr/bin/env node
// Writes the staged Claude Code and pi screens in demo/transcripts/:
//   claude-wide-N.ans  a 79-column pane (the status scenario): welcome box, prompt, tool calls with a diff, spinner, input box
//   claude-N.ans       the same session cut to 46 columns (paddock's preview shows 48 columns and the last 21 rows),
//                      sitting at the bottom of the pane: feat-preview
//   pi-N.ans           pi at 46 columns, working: tool blocks, "Working...", editor, footer
// Each file repaints the whole 35-row pane, bottom-anchored like the real TUIs; N counts the steps of the session.
//   node tools/demo/gen-agent-ui.mjs
// These imitate the agents' working UIs (staged, as every transcript here is); they are not captures.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { strWidth } from '../lib/wcwidth.mjs';

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), 'transcripts');
const ROWS = 35;
const E = '\x1b';

// ---- styling -------------------------------------------------------------

const sgr = (code, s) => `${E}[${code}m${s}${E}[0m`;
const dim = (s) => sgr(2, s);
const bold = (s) => sgr(1, s);
const green = (s) => sgr(32, s);
const orange = (s) => sgr('38;5;173', s); // claude's colour
const vis = (s) => strWidth(s.replace(/\x1b\[[0-9;]*m/g, ''));
const pad = (s, w) => s + ' '.repeat(Math.max(0, w - vis(s)));
/** A full-width band: PARTS are [sgr codes, text]; the background is BG. */
const band = (parts, w, bg) => {
  const n = parts.reduce((k, [, t]) => k + vis(t), 0);
  return parts.map(([c, t]) => `${E}[${[c, bg].filter(Boolean).join(';')}m${t}${E}[0m`).join('') + `${E}[${bg}m${' '.repeat(Math.max(0, w - n))}${E}[0m`;
};

function wrap(text, w) {
  const lines = [];
  let cur = '';
  for (const word of text.split(' ')) {
    if (cur && cur.length + 1 + word.length > w) { lines.push(cur); cur = word; } else cur = cur ? `${cur} ${word}` : word;
  }
  return lines.concat(cur);
}

/**
 * The screen: BODY lines flow down from row 1 (the last ones that fit stay), or, with BOTTOM, sit just above the
 * fixed rows, as in a session that has filled the pane. FIXED are [row, text] pairs.
 */
function screen(body, fixed, bottom = false) {
  const avail = Math.min(...fixed.map(([r]) => r)) - 1;
  const shown = body.slice(-avail);
  const rows = Array.from({ length: ROWS }, () => '');
  const top = bottom ? avail - shown.length : 0;
  shown.forEach((l, i) => { rows[top + i] = l; });
  for (const [r, t] of fixed) rows[r - 1] = t;
  if (rows.length !== ROWS) throw new Error('rows');
  const bytes = `${E}[2J` + rows.map((t, i) => `${E}[${i + 1};1H${t}`).join('\n');
  return bytes.replace(/\x1b/g, '\\e');
}

function write(name, comment, text, w) {
  for (const line of text.replace(/\\e\[[0-9;]*[A-Za-z]/g, '').split('\n')) {
    if (strWidth(line) > w) throw new Error(`${name}: ${vis(line)} is wider than ${w}`);
  }
  fs.writeFileSync(path.join(out, name), `# ${comment} (generated by demo/gen-agent-ui.mjs; the whole 35-row pane is repainted)\n${text}\n`);
}

// ---- claude code ---------------------------------------------------------

const GLYPH = ['✢', '✳', '✶', '✻', '✽'];
const VERB = ['Clauding', 'Pondering', 'Noodling', 'Percolating', 'Simmering', 'Noodling', 'Clauding', 'Pondering'];
const TOKENS = ['0.6k', '0.9k', '1.2k', '1.6k', '1.9k', '2.3k', '2.6k', '2.9k'];
const PROMPT = 'add rate limiting to the checkout API, 20 req/min per customer';

function claudeBody(w, step, { welcome, diff }) {
  const wide = w > 60;
  const L = [];
  const text = (t) => wrap(t, w - 2).forEach((l, i) => L.push((i ? '  ' : `${E}[97m●${E}[0m `) + l));
  const tool = (name, arg, result) => { L.push(`${green('●')} ${bold(name)}(${arg})`); result.forEach((r) => L.push(dim(`  ⎿  ${r}`))); };
  if (welcome) {
    const inner = Math.min(w - 2, 56);
    const row = (s) => dim('│') + pad(s, inner) + dim('│');
    L.push(dim('╭' + '─'.repeat(inner) + '╮'));
    L.push(row(` ${orange('✻')} Welcome to ${bold('Claude Code')}!`));
    L.push(row(''));
    L.push(row(dim('   /help for help, /status for your current setup')));
    L.push(row(''));
    L.push(row(dim('   cwd: ~/code/webshop/api')));
    L.push(dim('╰' + '─'.repeat(inner) + '╯'));
    L.push('');
  }
  const prompt = wrap(PROMPT, w - 3);
  prompt.forEach((p, i) => L.push(band([['', i ? '  ' : '> '], ['1', p]], w, '48;5;236')));
  L.push('');
  text("I'll start with how the checkout handlers are wired.");
  tool('Read', 'internal/http/checkout.go', ['Read 142 lines']);
  if (step >= 1) tool('Read', 'internal/http/router.go', ['Read 87 lines']);
  if (step >= 2) { L.push(''); text("A token bucket keyed on the customer id fits. I'll add it as middleware."); }
  if (step >= 3) tool('Write', 'internal/http/ratelimit.go', ['Wrote 58 lines']);
  if (step >= 4) {
    tool('Update', 'internal/http/router.go', [wide ? 'Updated internal/http/router.go with 2 additions and 1 removal' : 'Updated 3 lines']);
    if (diff) {
      const d = (n, sign, code) => {
        const bg = sign === '+' ? '48;2;24;56;34' : sign === '-' ? '48;2;72;30;34' : '';
        const line = `      ${String(n).padStart(3)} ${sign || ' '}   ${code}`;
        return bg ? band([['', line]], w - 2, bg) : dim(line);
      };
      L.push(d(18, '', 'mux.Handle("/health", health)'));
      L.push(d(19, '+', 'limiter := NewLimiter(20)'));
      L.push(d(20, '+', 'mux.Handle("/checkout", limiter.Wrap(checkout))'));
      L.push(d(21, '-', 'mux.Handle("/checkout", checkout)'));
    }
  }
  if (step >= 5) tool('Write', 'internal/http/ratelimit_test.go', ['Wrote 74 lines']);
  if (step >= 6) tool('Bash', 'go test ./...', [step >= 7 ? 'ok  internal/http  0.412s' : 'Running…']);
  if (step >= 8) {
    L.push('');
    text('Added a token-bucket limiter keyed on the customer id: requests past 20 a minute get a 429 with Retry-After. 4 tests pass.');
    L.push('');
    L.push(dim(`${E}[0m✻ Worked for 12s`));
  }
  return L;
}

function claudeScreen(w, step, opts) {
  const working = step < 8;
  const spin = working
    ? orange(`${GLYPH[step % 5]} ${VERB[step]}…`) + ' ' + dim(w > 60 ? `(${4 + step}s · ↑ ${TOKENS[step]} tokens · esc to interrupt)` : `(${4 + step}s · ↑ ${TOKENS[step]} tokens)`)
    : '';
  const box = [
    [ROWS - 3, dim('╭' + '─'.repeat(w - 2) + '╮')],
    [ROWS - 2, dim('│') + ` ${bold('>')}` + ' '.repeat(w - 4) + dim('│')],
    [ROWS - 1, dim('╰' + '─'.repeat(w - 2) + '╯')],
    [ROWS, dim('  ? for shortcuts')],
  ];
  return screen(claudeBody(w, step, opts), [[ROWS - 5, spin], ...box], !opts.welcome);
}

for (let step = 0; step <= 8; step++) {
  write(`claude-wide-${step}.ans`, `Claude Code at work, 79 columns, step ${step} of 8`, claudeScreen(78, step, { welcome: true, diff: true }), 78);
  write(`claude-${step}.ans`, `Claude Code at work, cut to 46 columns for the preview, step ${step} of 8`, claudeScreen(46, step, { welcome: false, diff: false }), 46);
}

// ---- pi ------------------------------------------------------------------

const BRAILLE = ['⠋', '⠙', '⠹', '⠸', '⠼', '⠴', '⠦', '⠧', '⠇', '⠏'];
const COST = ['0.021', '0.034', '0.046', '0.058', '0.071'];
const CTX = ['2.4', '2.9', '3.3', '3.6', '4.0'];
const TOOL_BG = '48;2;38;42;50';

function piScreen(w, step) {
  const L = [dim(' pi v0.99.0'), dim(' escape interrupt · ctrl+c/ctrl+d clear/exit'), ''];
  const block = (head, lines) => {
    L.push(band([['1', head]], w, TOOL_BG));
    lines.forEach(([style, t]) => L.push(band([[style, ' ' + t]], w, TOOL_BG)));
  };
  wrap('move staging onto the new vpc module', w - 2).forEach((l) => L.push(band([['', ' ' + l]], w, '48;2;52;53;65')));
  L.push('');
  L.push(' I\'ll check how staging uses the module.');
  L.push('');
  block(' read envs/staging/main.tf', [
    ['2', 'module "vpc" {'],
    ['2', '  source = "../modules/vpc-old"'],
    ['2', '  cidr   = "10.20.0.0/16"'],
    ['2', '... (93 more lines)'],
  ]);
  if (step >= 1) {
    L.push('');
    L.push(' Pointing it at the new module.');
    L.push('');
    block(' edit envs/staging/main.tf', [
      ['38;2;204;100;100', '-  source = "../modules/vpc-old"'],
      ['38;2;120;190;130', '+  source = "../modules/vpc"'],
    ]);
  }
  if (step >= 2) {
    L.push('');
    block(' $ terraform plan', [
      ['2', 'Refreshing state... [id=vpc-0a1b2c]'],
      ...(step >= 3 ? [['2', 'module.vpc.aws_subnet.private[0]: update']] : []),
      ...(step >= 3 ? [['2', 'module.vpc.aws_subnet.private[1]: update']] : []),
      ...(step >= 4 ? [['2', 'Plan: 0 to add, 4 to change, 0 to destroy.']] : []),
    ]);
  }
  if (step >= 4) { L.push(''); L.push(' Four in-place changes, nothing is'); }
  const line = sgr('2', '─'.repeat(w - 2));
  const stats = `$${COST[step]} ${CTX[step]}%/272k (auto)`;
  const model = 'sonnet-4 · medium';
  return screen(L, [
    [ROWS - 5, ` ${BRAILLE[(step * 3) % 10]} Working...`],
    [ROWS - 4, ' ' + line],
    [ROWS - 3, ' ' + dim('▏')],
    [ROWS - 2, ' ' + line],
    [ROWS - 1, ' ' + dim('~/code/infra')],
    [ROWS, ' ' + dim(stats + ' '.repeat(w - 2 - stats.length - model.length) + model)],
  ], true);
}

for (let step = 0; step <= 4; step++) write(`pi-${step}.ans`, `pi at work, 46 columns, step ${step} of 4`, piScreen(46, step), 46);
